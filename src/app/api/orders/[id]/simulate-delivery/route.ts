import { NextRequest, NextResponse } from "next/server";
import { getSessionUser } from "@/lib/server/session-helper";
import { prisma } from "@/lib/server/prisma";
import { ShipmentStatus, OrderStatus } from "@prisma/client";
import { orderService } from "@/lib/server/order-service";

interface Params {
  params: {
    id: string;
  };
}

export async function POST(request: NextRequest, { params }: Params) {
  const user = await getSessionUser();
  if (!user) {
    return NextResponse.json({ error: "Unauthorized access." }, { status: 401 });
  }

  const orderId = params.id;
  const order = await prisma.order.findFirst({
    where: { id: orderId, customerId: user.id },
    include: {
      items: true,
      shipments: { include: { trackingEvents: true } },
    },
  });

  if (!order) {
    return NextResponse.json({ error: "Order not found." }, { status: 404 });
  }

  const shipment = order.shipments[0];
  if (!shipment) {
    const trackingNo = `BLUEDART-${Math.floor(10000000 + Math.random() * 90000000)}IN`;
    const newShp = await prisma.shipment.create({
      data: {
        id: `shp_${Date.now()}`,
        orderId: order.id,
        sellerId: order.items ? (await prisma.orderItem.findFirst({ where: { orderId: order.id } }))?.vendorId || "usr_seller_01" : "usr_seller_01",
        provider: "SIMULATED_3PL",
        carrierName: "Blue Dart Air Express",
        trackingNumber: trackingNo,
        status: ShipmentStatus.LABEL_CREATED,
        trackingEvents: {
          create: [
            {
              status: ShipmentStatus.LABEL_CREATED,
              location: "Seller Studio Dispatch Hub",
              description: "Shipping label created and assigned to Blue Dart Air Express.",
              source: "SYSTEM",
            },
          ],
        },
      },
    });

    const refreshed = await orderService.getOrderById(user.id, orderId);
    return NextResponse.json({ success: true, order: refreshed, currentStatus: ShipmentStatus.LABEL_CREATED });
  }

  const statusCycle: {
    from: ShipmentStatus;
    to: ShipmentStatus;
    desc: string;
    location: string;
    orderStatus?: OrderStatus;
  }[] = [
    {
      from: ShipmentStatus.PENDING_FULFILLMENT,
      to: ShipmentStatus.LABEL_CREATED,
      desc: "Shipping label generated by artisan maker.",
      location: "Maker Workshop, Mumbai",
    },
    {
      from: ShipmentStatus.LABEL_CREATED,
      to: ShipmentStatus.PICKUP_SCHEDULED,
      desc: "Pickup scheduled with Blue Dart courier van.",
      location: "Maker Workshop, Mumbai",
    },
    {
      from: ShipmentStatus.PICKUP_SCHEDULED,
      to: ShipmentStatus.SHIPPED,
      desc: "Package picked up by courier and in transit to hub.",
      location: "Blue Dart Sorting Center, Mumbai",
      orderStatus: OrderStatus.SHIPPED,
    },
    {
      from: ShipmentStatus.SHIPPED,
      to: ShipmentStatus.IN_TRANSIT,
      desc: "In transit through regional transit express corridor.",
      location: "Central Air Freight Cargo Terminal",
      orderStatus: OrderStatus.SHIPPED,
    },
    {
      from: ShipmentStatus.IN_TRANSIT,
      to: ShipmentStatus.OUT_FOR_DELIVERY,
      desc: "Out for delivery with delivery associate. Expect arrival today.",
      location: "Local Delivery Center, Patron City",
      orderStatus: OrderStatus.SHIPPED,
    },
    {
      from: ShipmentStatus.OUT_FOR_DELIVERY,
      to: ShipmentStatus.DELIVERED,
      desc: "Consignment securely handed over to patron. Escrow released.",
      location: "Patron Delivery Destination",
      orderStatus: OrderStatus.DELIVERED,
    },
  ];

  const currentIdx = statusCycle.findIndex((c) => c.from === shipment.status);
  const nextStep = currentIdx >= 0 ? statusCycle[currentIdx] : null;

  if (!nextStep) {
    const refreshed = await orderService.getOrderById(user.id, orderId);
    return NextResponse.json({
      success: true,
      message: "Order already reached final destination milestone (Delivered).",
      order: refreshed,
      currentStatus: shipment.status,
    });
  }

  await prisma.$transaction([
    prisma.shipment.update({
      where: { id: shipment.id },
      data: {
        status: nextStep.to,
        dispatchedAt: nextStep.to === ShipmentStatus.SHIPPED ? new Date() : undefined,
        deliveredAt: nextStep.to === ShipmentStatus.DELIVERED ? new Date() : undefined,
      },
    }),
    prisma.shipmentTrackingEvent.create({
      data: {
        shipmentId: shipment.id,
        status: nextStep.to,
        location: nextStep.location,
        description: nextStep.desc,
        source: "CARRIER_SYNC",
      },
    }),
    ...(nextStep.orderStatus
      ? [
          prisma.order.update({
            where: { id: order.id },
            data: { status: nextStep.orderStatus },
          }),
          prisma.auditEvent.create({
            data: {
              entityType: "ORDER",
              entityId: order.id,
              action: `ORDER_${nextStep.to}`,
              note: `Carrier sync: ${nextStep.desc} (${nextStep.location})`,
              performedBy: "system:carrier_sync",
            },
          }),
        ]
      : []),
  ]);

  const updatedOrder = await orderService.getOrderById(user.id, orderId);
  return NextResponse.json({
    success: true,
    order: updatedOrder,
    currentStatus: nextStep.to,
    message: nextStep.desc,
  });
}
